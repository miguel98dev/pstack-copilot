import { join } from "node:path";
import type { Adapter, Feature } from "../build/adapter.ts";
import { copilotValue } from "../build/models.ts";
import { parseFrontmatter } from "../lib/frontmatter.ts";
import { exists, readJson, readText } from "../lib/fs.ts";
import type { ItemChange, UpstreamDiff } from "./diff.ts";
import type { Impact } from "./impact.ts";
import type { UpstreamLock } from "./lock.ts";

/**
 * The only files a sync may write in the adapter. Overlays, terms.json, models.json, the adapter skill, and the
 * docs are custom Copilot work, so the sync reports what they need and leaves them alone.
 */
export const MIGRATABLE = ["adapter.json", "mappings/features.json", "mappings/agents.json", "mappings/skills.json"] as const;

export interface MigrationPlan {
	/** New contents by path relative to the adapter folder, only for files that change. */
	readonly files: ReadonlyMap<string, string>;
	/** One line per change, for the report and the history. */
	readonly ops: readonly string[];
	/** Things the sync meant to add that were already there, and so were kept as they are. */
	readonly kept: readonly string[];
	readonly revision: { readonly before: number; readonly after: number };
	readonly coreVersions: readonly string[];
}

type Json = Record<string, unknown>;

export interface MigrationInput {
	readonly adapterDir: string;
	readonly adapter: Adapter;
	readonly diff: UpstreamDiff;
	readonly impact: Impact;
	readonly oldLock: UpstreamLock | null;
	readonly newLock: UpstreamLock;
	readonly newRoot: string;
}

function ids(item: ItemChange, which: "new" | "old"): string {
	return `${item.kind}:${which === "old" && item.from ? item.from : item.name}`;
}

function stub(id: string, version: string): Feature {
	const kind = id.slice(0, id.indexOf(":")) as Feature["kind"];
	return { id, kind, status: "pending", copilot: `New in upstream ${version}. Not reviewed for Copilot yet.`, validation: "untested" };
}

function insertFeature(features: Json[], entry: Json): void {
	let at = -1;
	features.forEach((feature, index) => {
		if (feature.kind === entry.kind) at = index;
	});
	if (at < 0) features.push(entry);
	else features.splice(at + 1, 0, entry);
}

const DROP_ALWAYS = new Set(["name", "description"]);

/** Derives an agent rule from the upstream agent's frontmatter: keep name and description, drop the rest, map a model slug. */
export function deriveAgentRule(text: string, adapter: Adapter): { drop: string[]; set: Json; why: string } {
	const fm = parseFrontmatter(text);
	const drop = fm.entries.map((entry) => entry.key).filter((key) => !DROP_ALWAYS.has(key));
	const set: Json = {};
	const model = fm.entries.find((entry) => entry.key === "model");
	if (model && typeof model.value === "string") {
		try {
			const [id, effort] = copilotValue(model.value, adapter.models).split(" @");
			set.model = id;
			if (effort) set["reasoning-effort"] = effort;
		} catch {
			/* no Copilot mapping for this slug: the agent inherits the session model */
		}
	}
	set["user-invocable"] = false;
	return { drop, set, why: `Generated by the upstream sync from the agent's frontmatter. It drops ${drop.length > 0 ? drop.join(", ") : "nothing"} because Copilot has no equivalent field, and hides the agent from the picker as a delegate. Review it.` };
}

function readRaw(dir: string, rel: string): Json {
	return readJson(join(dir, rel)) as Json;
}

function stringify(value: unknown): string {
	return `${JSON.stringify(value, null, "\t")}\n`;
}

export function planMigration(input: MigrationInput): MigrationPlan {
	const { adapterDir, adapter, diff, newLock, newRoot } = input;
	const files = new Map<string, string>();
	const ops: string[] = [];
	const kept: string[] = [];

	const featuresDoc = readRaw(adapterDir, "mappings/features.json");
	const features = (featuresDoc.features as Json[]).map((feature) => ({ ...feature }));
	const byId = (id: string) => features.findIndex((feature) => feature.id === id);
	const agentsDoc = readRaw(adapterDir, "mappings/agents.json");
	const agents = { ...(agentsDoc.agents as Record<string, Json>) };
	const skillsDoc = readRaw(adapterDir, "mappings/skills.json");
	const hints = { ...(skillsDoc.skills as Record<string, Json>) };
	let featuresChanged = false;
	let agentsChanged = false;
	let hintsChanged = false;

	const addFeature = (id: string, why: string) => {
		if (byId(id) >= 0) {
			kept.push(`features.json already has ${id}; kept as it is`);
			return;
		}
		insertFeature(features, stub(id, newLock.version) as unknown as Json);
		featuresChanged = true;
		ops.push(`features.json: added ${id} as pending (${why})`);
	};
	const removeFeature = (id: string, why: string) => {
		const at = byId(id);
		if (at < 0) return;
		features.splice(at, 1);
		featuresChanged = true;
		ops.push(`features.json: removed ${id} (${why})`);
	};
	const markStale = (id: string, why: string) => {
		const at = byId(id);
		if (at < 0 || features[at].validation !== "vscode-validated") return;
		const note = `Upstream changed this in ${newLock.version}; the VS Code run no longer proves it. Rerun the scenario.`;
		features[at] = { ...features[at], validation: "stale", limits: typeof features[at].limits === "string" && features[at].limits ? `${features[at].limits} ${note}` : note };
		featuresChanged = true;
		ops.push(`features.json: marked ${id} stale (${why})`);
	};

	for (const item of diff.items) {
		if (item.kind === "automation" && item.change === "modified") continue;
		if (item.change === "added") {
			addFeature(ids(item, "new"), `new upstream ${item.kind}`);
			if (item.kind === "agent") {
				if (agents[item.name]) kept.push(`agents.json already has a rule for ${item.name}; kept as it is`);
				else {
					const file = join(newRoot, `agents/${item.name}.md`);
					if (exists(file)) {
						agents[item.name] = deriveAgentRule(readText(file), adapter);
						agentsChanged = true;
						ops.push(`agents.json: added a derived rule for ${item.name}`);
					}
				}
			}
		} else if (item.change === "removed") {
			removeFeature(ids(item, "new"), `upstream ${item.kind} deleted`);
			if (item.kind === "agent" && agents[item.name]) {
				delete agents[item.name];
				agentsChanged = true;
				ops.push(`agents.json: removed the rule for ${item.name}`);
			}
			if (item.kind === "skill" && hints[item.name]) {
				delete hints[item.name];
				hintsChanged = true;
				ops.push(`skills.json: removed the argument-hint for ${item.name}`);
			}
		} else if (item.change === "renamed" && item.from) {
			const from = ids(item, "old");
			const to = ids(item, "new");
			const at = byId(from);
			if (at >= 0 && byId(to) < 0) {
				features[at] = { ...features[at], id: to };
				featuresChanged = true;
				ops.push(`features.json: renamed ${from} to ${to}`);
				markStale(to, `${item.kind} renamed`);
			} else if (at >= 0) {
				kept.push(`features.json already has ${to}; the entry ${from} was removed instead of renamed`);
				removeFeature(from, "upstream renamed it and the new id already exists");
			} else addFeature(to, `renamed upstream ${item.kind}`);
			if (item.kind === "agent" && agents[item.from] && !agents[item.name]) {
				agents[item.name] = agents[item.from];
				delete agents[item.from];
				agentsChanged = true;
				ops.push(`agents.json: renamed the rule ${item.from} to ${item.name}`);
			}
			if (item.kind === "skill" && hints[item.from] && !hints[item.name]) {
				hints[item.name] = hints[item.from];
				delete hints[item.from];
				hintsChanged = true;
				ops.push(`skills.json: renamed the argument-hint ${item.from} to ${item.name}`);
			}
		} else if (item.change === "modified") markStale(ids(item, "new"), `upstream ${item.kind} changed`);
	}
	for (const key of diff.vocabulary.added) addFeature(`term:${key}`, "new Cursor term");
	for (const key of diff.vocabulary.removed) removeFeature(`term:${key}`, "upstream dropped the term");

	for (const unit of Object.keys(hints)) {
		const file = join(newRoot, `skills/${unit}/SKILL.md`);
		if (!exists(file)) continue;
		const keys = parseFrontmatter(readText(file)).entries.map((entry) => entry.key);
		const duplicated = Object.keys(hints[unit]).filter((key) => keys.includes(key));
		if (duplicated.length > 0) {
			delete hints[unit];
			hintsChanged = true;
			ops.push(`skills.json: dropped the ${duplicated.join(", ")} hint for ${unit}, which upstream now sets itself`);
		}
	}

	if (featuresChanged) files.set("mappings/features.json", stringify({ ...featuresDoc, features }));
	if (agentsChanged) files.set("mappings/agents.json", stringify({ ...agentsDoc, agents }));
	if (hintsChanged) files.set("mappings/skills.json", stringify({ ...skillsDoc, skills: hints }));

	const adapterDoc = readRaw(adapterDir, "adapter.json");
	const revisionBefore = adapter.revision;
	const revisionAfter = revisionBefore + 1;
	const coreVersions = [newLock.version];
	files.set("adapter.json", stringify({ ...adapterDoc, revision: revisionAfter, coreVersions }));
	ops.push(`adapter.json: coreVersions is now ${newLock.version}, revision ${revisionBefore} -> ${revisionAfter}`);

	for (const path of files.keys()) {
		if (!(MIGRATABLE as readonly string[]).includes(path)) throw new Error(`migration tried to write ${path}, which is custom Copilot work`);
	}
	return { files, ops, kept, revision: { before: revisionBefore, after: revisionAfter }, coreVersions };
}
