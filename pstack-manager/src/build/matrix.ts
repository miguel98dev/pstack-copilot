import type { UpstreamLock } from "../upstream/lock.ts";
import type { Adapter, Feature } from "./adapter.ts";

const STATUS: Record<Feature["status"], string> = {
	native: "Native",
	adapted: "Adapted",
	partial: "Partial",
	unsupported: "Unsupported",
	excluded: "Not shipped",
};

const VALIDATION: Record<Feature["validation"], string> = {
	"vscode-validated": "Validated in VS Code",
	static: "Build and tests only",
	untested: "Not tested",
};

const SECTIONS: readonly { kind: Feature["kind"]; title: string }[] = [
	{ kind: "skill", title: "Skills" },
	{ kind: "playbook", title: "poteto-mode playbooks" },
	{ kind: "agent", title: "Agents" },
	{ kind: "script", title: "Scripts" },
	{ kind: "term", title: "Cursor features and names" },
	{ kind: "automation", title: "Automations" },
	{ kind: "copilot-addition", title: "Added by this port" },
];

function cell(text: string | undefined): string {
	return (text || "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

/** Renders the compatibility matrix that ships inside the adapter skill. Generated, so it never drifts from the mapping data. */
export function renderMatrix(adapter: Adapter, lock: UpstreamLock, version: string): string {
	const counts = new Map<string, number>();
	for (const feature of adapter.features) counts.set(feature.validation, (counts.get(feature.validation) || 0) + 1);
	let out = `# pstack ${version} on GitHub Copilot: compatibility\n\n`;
	out += `Generated by pstack-manager from \`pstack-${adapter.id}/mappings/features.json\` for upstream pstack ${lock.version} (\`${lock.commit.slice(0, 12)}\`). Do not edit by hand.\n\n`;
	out += "Status: **Native** works as upstream wrote it. **Adapted** works through the mapping in the pstack-copilot skill. **Partial** works with a documented loss. **Unsupported** depends on a Cursor-only service; the skill is shipped and skips the step with one line. **Not shipped** is left out of the build.\n\n";
	out += `Validation: **Validated in VS Code** ran in a real VS Code Copilot session with the evidence named. **Build and tests only** is checked by the build, the validator, and automated tests, but was not run by an agent. **Not tested** has no check yet. Counts: ${[...counts].map(([state, n]) => `${VALIDATION[state as Feature["validation"]]} ${n}`).join(", ")}.\n`;
	for (const { kind, title } of SECTIONS) {
		const rows = adapter.features.filter((feature) => feature.kind === kind);
		if (rows.length === 0) continue;
		out += `\n## ${title}\n\n| Feature | Status | On Copilot | Validation | Limits |\n| --- | --- | --- | --- | --- |\n`;
		for (const feature of rows) {
			const validation = feature.evidence ? `${VALIDATION[feature.validation]}: ${feature.evidence}` : VALIDATION[feature.validation];
			out += `| \`${cell(feature.id.replace(/^[a-z-]+:/, ""))}\` | ${STATUS[feature.status]} | ${cell(feature.copilot)} | ${cell(validation)} | ${cell(feature.limits)} |\n`;
		}
	}
	return out;
}
